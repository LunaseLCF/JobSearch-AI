const fs = require('fs');
const path = require('path');

const rawOrigin = String(process.env.BACKEND_ORIGIN || '').trim();
if (!rawOrigin) {
  console.error('BACKEND_ORIGIN is required. Example: https://careercompass-ai.onrender.com');
  process.exit(1);
}

let parsed;
try {
  parsed = new URL(rawOrigin);
} catch (error) {
  console.error('BACKEND_ORIGIN must be a valid URL. Received: ' + rawOrigin);
  process.exit(1);
}

if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') {
  console.error('BACKEND_ORIGIN must use http or https. Received: ' + rawOrigin);
  process.exit(1);
}

const basePath = parsed.pathname === '/' ? '' : parsed.pathname.replace(/\/+$/, '');
const origin = parsed.origin + basePath;

const proxyRoutes = [
  '/api/*',
  '/api',
  '/login',
  '/login.html',
  '/register',
  '/register.html',
  '/reset-password',
  '/reset-password.html',
  '/admin',
  '/admin.html',
  '/login_page_ref.jpg',
  '/favicon.ico',
];

function targetFor(route) {
  if (route.endsWith('/*')) {
    return origin + route.slice(0, -1) + ':splat';
  }
  return origin + route;
}

const lines = [
  '# Generated by scripts/write-netlify-redirects.js. Do not edit by hand.',
  '# Static files in public/ are served first; everything below proxies to the Node backend.',
];

proxyRoutes.forEach(route => {
  lines.push(`${route}  ${targetFor(route)}  200`);
});

// Keep this last so API and auth routes above match first.
lines.push('/*  /index.html  200');

const outputFile = path.join(__dirname, '..', 'public', '_redirects');
fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(outputFile, lines.join('\n') + '\n', 'utf8');

console.log('Wrote ' + path.relative(process.cwd(), outputFile) + ' for backend ' + origin);
