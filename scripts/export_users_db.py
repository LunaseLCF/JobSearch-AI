"""Build the registered-users workbook from the live SQLite-backed user list.

Usage: python export_users_db.py <payload.json> <output.xlsx>
The payload is generated by server/index.js so Python stays free of app logic.
"""

import json
import sys
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter


def style_header(ws, widths):
    fill = PatternFill("solid", fgColor="1F2937")
    for index, width in enumerate(widths, start=1):
        cell = ws.cell(row=1, column=index)
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = fill
        cell.alignment = Alignment(vertical="center")
        ws.column_dimensions[get_column_letter(index)].width = width
    ws.freeze_panes = "A2"


def main():
    if len(sys.argv) != 3:
        raise SystemExit("usage: export_users_db.py <payload.json> <output.xlsx>")

    payload = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    output = Path(sys.argv[2])
    output.parent.mkdir(parents=True, exist_ok=True)

    wb = Workbook()

    users_ws = wb.active
    users_ws.title = "Users"
    users_ws.append(["ID", "Name", "Email", "Password", "Registered At", "Status", "User Level"])
    for user in payload.get("users", []):
        users_ws.append([
            user.get("id", ""),
            user.get("name", ""),
            user.get("email", ""),
            "(hashed in database)",
            user.get("registeredAt", ""),
            user.get("status", "Active"),
            user.get("level", "free"),
        ])
    style_header(users_ws, [22, 24, 34, 24, 28, 14, 14])

    plans = payload.get("plans", {})
    levels_ws = wb.create_sheet("User Levels")
    levels_ws.append(["Level", "Feature", "Enabled", "Monthly Limit"])
    for name, definition in plans.items():
        features = definition.get("features", {})
        limits = definition.get("limits", {})
        for feature in features:
            limit = limits.get(feature, 0)
            levels_ws.append([
                definition.get("label", name),
                feature,
                "Yes" if features.get(feature) else "No",
                "Unlimited" if limit is None or limit == float("inf") or limit == "Infinity" else limit,
            ])
    style_header(levels_ws, [14, 18, 12, 18])

    wb.save(output)


if __name__ == "__main__":
    main()
